### Sobre python:    
    ## Lenguaje de programación de alto nivel, 
    ## multiparadigma: Permite usar múltiples estilos de programación según convenga, en lugar de obligarte a seguir uno solo (Funcional, POO, Procedimental...). 
    ## Interpretado: El intérprete (CPython) traduce el código a un formato intermedio (bytecode) y lo ejecuta en tiempo real, sin requerir una compilación previa a binario ejecutable.
    ## Tipado Dinámico: No se declaran los tipos de las variables; el tipo se determina automáticamente durante la ejecución según el valor asignado.
    ## Tipado Fuerte: No realiza conversiones implícitas de tipos incompatibles (por ejemplo, "10" + 5 genera un TypeError en lugar de convertir el número a texto).

